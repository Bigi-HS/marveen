// C12 chameleon canary harness (kanban 6d8b5f70).
//
// One persistent sandbox agent ("buster") that normally just exists at
// baseline and serves as a launcher/config/monitor canary: it dies first if
// the launch path breaks, warning us before a live agent dies, and keeps the
// keep-alive / MCP pipe warm.
//
// To validate a change to an agent we:
//   1. morph(target)  -- rebuild the sandbox as a disposable clone of `target`
//   2. smoke(...)      -- launch, survive a window, answer an inter-agent ping
//   3. promote(target) -- copy the validated files into the LIVE target
//   4. revert()        -- clean rebuild of the sandbox back to baseline
//
// Hard constraints (from the C12 spec):
//   - DISTINCT session name (`agent-buster`), never a shared name -- guaranteed
//     by deriving the session from the sandbox agent name.
//   - PID-only kills (never `pkill -f`): we reuse stopAgentProcess, which kills
//     the named tmux session and reaps orphans by explicit PID (see
//     channel-poller-reap.ts). No process is matched by command-line substring.
//   - NEVER the real channel token: morph copies config but no channels/ token,
//     and forces channel-less + shared auth so the clone cannot 409 against the
//     original or spend on its API key.
//   - Clean attribution: the morphed CLAUDE.md carries a banner telling the
//     clone to identify itself as "buster" in all mail/cost, never as `target`.
//   - "revert to baseline" is a CLEAN REBUILD (destroy + recreate from the
//     baseline snapshot), NOT an in-place undo, so residue from a previous
//     morph (memory, sessions, .claude.json projects, tokens) cannot bleed into
//     the next test and make it lie.
//
// Architecture mirrors the rest of src/web: pure decision/transform functions
// (exported, unit-tested with no fs/tmux) and thin IO wrappers around them.

